class Command(BaseCommand):
    help = 'Створює стандартні сторінки (Pages) та FAQ з українським текстом без дублів'

    def handle(self, *args, **options):
        from core.models import Page, FAQ

        created_p = updated_p = 0
        for data in PAGES:
            obj, created = Page.objects.get_or_create(slug=data['slug'])
            for key, val in data.items():
                if key != 'slug':
                    setattr(obj, key, val)
            obj.save()
            if created:
                created_p += 1
            else:
                updated_p += 1

        self.stdout.write(f'  Pages: {created_p} створено, {updated_p} оновлено')

        created_f = 0
        for data in FAQS:
            defaults = {k: v for k, v in data.items() if k != 'question_uk'}
            defaults['is_published'] = True
            _, created = FAQ.objects.get_or_create(
                question_uk=data['question_uk'],
                defaults=defaults,
            )
            if created:
                created_f += 1

        self.stdout.write(f'  FAQs: {created_f} створено')
        self.stdout.write(self.style.SUCCESS(
            f'Усього Pages: {Page.objects.count()}, FAQs: {FAQ.objects.count()}'
        ))
